const stored = typeof localStorage === 'undefined' ? null : localStorage.getItem(STORAGE_KEY)
export const language = ref<Language>(stored === 'en' ? 'en' : 'ko')

export function setLanguage(lang: Language) {
  language.value = lang
  localStorage.setItem(STORAGE_KEY, lang)
}

export function tm(key: string, vars?: Record<string, string | number>): string | undefined {
  const template = messages[language.value][key] ?? messages.ko[key]
  if (!template) return undefined
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars?.[name] ?? `{${name}}`))
}

export function t(key: string, vars?: Record<string, string | number>): string {
  return tm(key, vars) ?? key
}
